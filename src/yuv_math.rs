/// Port of `SkColorMatrix_RGB2YUV`.
pub fn sk_color_matrix_rgb_to_yuv(cs: SkYUVColorSpace, m: &mut [f32; 20]) {
    *m = match cs {
        SkYUVColorSpace::Identity => IDENTITY,
        _ => RGB_TO_YUV[cs as usize],
    };
}

/// Port of `SkColorMatrix_YUV2RGB`.
pub fn sk_color_matrix_yuv_to_rgb(cs: SkYUVColorSpace, m: &mut [f32; 20]) {
    *m = match cs {
        SkYUVColorSpace::Identity => IDENTITY,
        _ => YUV_TO_RGB[cs as usize],
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn identity_and_known_jpeg_rows() {
        let mut m = [0.0; 20];
        sk_color_matrix_rgb_to_yuv(SkYUVColorSpace::Identity, &mut m);
        assert_eq!(m, IDENTITY);
        sk_color_matrix_rgb_to_yuv(SkYUVColorSpace::JpegFull, &mut m);
        assert_eq!(&m[..5], &[0.299, 0.587, 0.114, 0.0, 0.0]);
        sk_color_matrix_yuv_to_rgb(SkYUVColorSpace::JpegFull, &mut m);
        assert_eq!(&m[..5], &[1.0, -0.0, 1.402, 0.0, -0.703749]);
    }
}
