#![allow(clippy::excessive_precision)]

//! YUV color matrices from `src/core/SkYUVMath.cpp`.
//!
//! The pinned Skia source generates two 20-float, row-major matrices for each
//! color space.  The portable build uses the low-precision (`#else`) tables;
//! those values are reproduced verbatim here.  Skia's debug-only table dump
//! helper is intentionally not ported: it is a code-generation diagnostic and
//! is not part of the runtime matrix lookup path.

#[repr(i32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SkYUVColorSpace {
    JpegFull = 0,
    Rec601Limited = 1,
    Rec709Full = 2,
    Rec709Limited = 3,
    Bt2020_8bitFull = 4,
    Bt2020_8bitLimited = 5,
    Bt2020_10bitFull = 6,
    Bt2020_10bitLimited = 7,
    Bt2020_12bitFull = 8,
    Bt2020_12bitLimited = 9,
    Bt2020_16bitFull = 10,
    Bt2020_16bitLimited = 11,
    FccFull = 12,
    FccLimited = 13,
    Smpte240Full = 14,
    Smpte240Limited = 15,
    YdzdxFull = 16,
    YdzdxLimited = 17,
    GbrFull = 18,
    GbrLimited = 19,
    Ycgco8bitFull = 20,
    Ycgco8bitLimited = 21,
    Ycgco10bitFull = 22,
    Ycgco10bitLimited = 23,
    Ycgco12bitFull = 24,
    Ycgco12bitLimited = 25,
    Ycgco16bitFull = 26,
    Ycgco16bitLimited = 27,
    Identity = 28,
}

impl SkYUVColorSpace {
    pub const LAST_ENUM: Self = Self::Identity;

    pub const JPEG: Self = Self::JpegFull;
    pub const REC601: Self = Self::Rec601Limited;
    pub const REC709: Self = Self::Rec709Limited;
    pub const BT2020: Self = Self::Bt2020_8bitLimited;

    pub const fn as_i32(self) -> i32 {
        self as i32
    }

    pub const fn from_i32(value: i32) -> Option<Self> {
        match value {
            0 => Some(Self::JpegFull),
            1 => Some(Self::Rec601Limited),
            2 => Some(Self::Rec709Full),
            3 => Some(Self::Rec709Limited),
            4 => Some(Self::Bt2020_8bitFull),
            5 => Some(Self::Bt2020_8bitLimited),
            6 => Some(Self::Bt2020_10bitFull),
            7 => Some(Self::Bt2020_10bitLimited),
            8 => Some(Self::Bt2020_12bitFull),
            9 => Some(Self::Bt2020_12bitLimited),
            10 => Some(Self::Bt2020_16bitFull),
            11 => Some(Self::Bt2020_16bitLimited),
            12 => Some(Self::FccFull),
            13 => Some(Self::FccLimited),
            14 => Some(Self::Smpte240Full),
            15 => Some(Self::Smpte240Limited),
            16 => Some(Self::YdzdxFull),
            17 => Some(Self::YdzdxLimited),
            18 => Some(Self::GbrFull),
            19 => Some(Self::GbrLimited),
            20 => Some(Self::Ycgco8bitFull),
            21 => Some(Self::Ycgco8bitLimited),
            22 => Some(Self::Ycgco10bitFull),
            23 => Some(Self::Ycgco10bitLimited),
            24 => Some(Self::Ycgco12bitFull),
            25 => Some(Self::Ycgco12bitLimited),
            26 => Some(Self::Ycgco16bitFull),
            27 => Some(Self::Ycgco16bitLimited),
            28 => Some(Self::Identity),
            _ => None,
        }
    }
}

